import { defineConfig } from 'vite-plus';

/**
 * Vite+ toolchain configuration: formatting, linting, the test runner, and the
 * host bundle.
 *
 * The whole toolchain is Vite+ — `vp fmt`, `vp lint`, `vp test`, `vp check` and
 * `vp pack`. The suite runs on Vitest, imported as `vite-plus/test` so the types
 * come from the toolchain rather than a second, separately-versioned copy of it.
 */
export default defineConfig({
  fmt: {
    // The repo is single-quoted throughout; oxfmt defaults to double quotes and
    // would otherwise rewrite every string literal for no reason.
    singleQuote: true,
    ignorePatterns: [
      // Captured incident evidence: byte-for-byte records of real sessions that
      // `test/replay.test.ts` hashes and replays. Reformatting them would edit
      // the evidence rather than the code.
      'test/fixtures/**',
      // Generated by `vp pack`. Reformatting it would make the committed bundle
      // differ from what a build produces, so `vp check` would fail on every
      // run after every build. `lib/client.js` is hand-written and deliberately
      // NOT ignored.
      'lib/index.js',
    ],
  },
  lint: {
    ignorePatterns: ['test/fixtures/**', 'lib/index.js'],
  },
  pack: {
    entry: ['src/index.ts'],
    outDir: 'lib',
    format: 'esm',
    platform: 'node',
    // `clean` defaults to **true**, and this output directory also holds
    // `lib/client.js`, which is hand-written and not generated by anything.
    // Leaving the default would delete it on every build.
    clean: false,
    // The package entry is `lib/index.js`. Pack names its output from the entry
    // (`index.mjs`), so the extension is pinned rather than renaming the entry
    // point across `package.json`, the manifest test and the DSH loader.
    outExtensions: () => ({ js: '.js' }),
    // Nothing is bundled: `src/` imports no package at all, and the one dynamic
    // import (the harness) must resolve at run time against the host's own copy.
    // A second copy inside this bundle is the exact failure the plugin guards
    // against.
    deps: { neverBundle: [/^@deepseek-ai\//] },
    // The bundle is committed and diffed; a size report is noise here.
    report: false,
    dts: false,
  },
  test: {
    // Explicit rather than the default glob, so a stray `.test.ts` elsewhere in
    // the tree cannot silently join the suite.
    include: ['test/**/*.test.ts'],
    // Isolation stays on (the default). Several files patch a shared prototype
    // or set `process.env`, and `loader.test.ts` depends on each file owning its
    // own module registry. Turning this off for speed would make those pass for
    // the wrong reason.
    isolate: true,
  },
  staged: {
    // Runs on the files Git has staged, via `.vite-hooks/pre-commit`. Format and
    // lint only: the full gate (typechecks, suite, mutation, upstream) belongs in
    // CI, where it cannot be skipped with `--no-verify`.
    '*.{ts,mts}': ['vp fmt', 'vp lint'],
    '*.{json,md,yml,yaml}': 'vp fmt',
  },
});
